static int rtk_dprx_set_dft_edid(struct rtk_dprx *dprx)
{
	u32 i;

	dprx->rbus_ops->write(DPRX14_DDC1_DDC_SIR, 0x0); /* start addr */
	for (i = 0; i < EDID_SIZE; i++)
		dprx->rbus_ops->write(DPRX14_DDC1_DDC_SAP, dft_2k_edid[i]);

	/* Dump edid sram */
	dprx->rbus_ops->write(DPRX14_DDC1_DDC_SIR, 0x0); /* start addr */
	for (i = 0; i < EDID_SIZE; i += 16) {
		u32 val[16];
		int j;

		for (j = 0; j < 16; j++)
			dprx->rbus_ops->read(DPRX14_DDC1_DDC_SAP, &val[j]);

		dev_info(dprx->dev, "EDID[0x%02x]: %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x\n",
			 i,
			 val[0], val[1], val[2], val[3],
			 val[4], val[5], val[6], val[7],
			 val[8], val[9], val[10], val[11],
			 val[12], val[13], val[14], val[15]);
	}

	/* OPEN EDID en */
	dprx->rbus_ops->write(DPRX14_DDC1_EDID_CR,
		DPRX14_DDC1_EDID_CR_EDID_SRWEN(1) |
		DPRX14_DDC1_EDID_CR_EDID_EN(1));

	return 0;
}

static const struct rtk_dprx_edid_ops dprx_edid_ops = {
	.set_dft = rtk_dprx_set_dft_edid,
};

int rtk_dprx_edid_init(struct rtk_dprx *dprx)
{

	dprx->edid_ops = &dprx_edid_ops;

	return 0;
}
